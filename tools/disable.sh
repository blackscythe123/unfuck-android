#!/usr/bin/env bash
# ==============================================================================
# CleanYourPhone - Safe Debloat Execution Script (Bash)
# Disables or uninstalls bloatware packages for User 0 over ADB.
#
# Usage:
#   tools/disable.sh lists/oppo/coloros-safe-debloat.txt
#   tools/disable.sh --mode uninstall lists/oppo/coloros-safe-debloat.txt
#   tools/disable.sh --dry-run lists/oppo/coloros-safe-debloat.txt
# ==============================================================================

set -euo pipefail

MODE="disable"
DRY_RUN=0
INSTALL_LAUNCHER=0
KEEP_LAUNCHER=0
LIST=""

# Parse arguments
while [[ $# -gt 0 ]]; do
  case "$1" in
    --mode)
      MODE="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --install-launcher)
      INSTALL_LAUNCHER=1
      shift
      ;;
    --keep-launcher)
      KEEP_LAUNCHER=1
      shift
      ;;
    *)
      LIST="$1"
      shift
      ;;
  esac
done

if [ -z "$LIST" ]; then
  echo "Usage: tools/disable.sh [--mode disable|uninstall] [--dry-run] <package-list.txt>" >&2
  exit 1
fi

if [ ! -f "$LIST" ]; then
  echo "Error: Package list file not found: $LIST" >&2
  exit 1
fi

# Ensure ADB is available
if ! command -v adb >/dev/null 2>&1; then
  echo "Error: 'adb' executable not found in PATH. Install Android platform-tools." >&2
  exit 1
fi

# Check connected device
DEVICE_COUNT=$(adb devices | grep -v "List of devices" | grep "device$" | wc -l | tr -d ' ')
if [ "$DEVICE_COUNT" -eq 0 ]; then
  echo "Error: No Android device detected over ADB." >&2
  echo "Check USB cable connection or run 'adb connect <phone-ip>:5555' for wireless ADB." >&2
  exit 1
fi

BRAND=$(adb shell getprop ro.product.brand | tr -d '\r')
MODEL=$(adb shell getprop ro.product.model | tr -d '\r')
SDK_VER=$(adb shell getprop ro.build.version.sdk | tr -dc '0-9')
[ -z "$SDK_VER" ] && SDK_VER=28

echo "=========================================================="
echo " Connected Device: $BRAND $MODEL (Android SDK $SDK_VER)"
echo " Debloat Mode    : $MODE (All OS variants supported)"
if [ "$DRY_RUN" -eq 1 ]; then
  echo " Execution Mode  : DRY RUN (no modifications will be made)"
fi
echo "=========================================================="

# Normalize list (remove BOM, CRLF, comments, trailing whitespace)
PKGS=$(awk 'NR==1{sub(/^\xef\xbb\xbf/,"")} {sub(/\r$/,""); print}' "$LIST" \
  | grep -vE '^\s*(#|$)' | sed -E 's/[[:space:]]+#.*$//' | awk '{print $1}')

if [ -z "$PKGS" ]; then
  echo "Error: No valid package names found in $LIST." >&2
  exit 1
fi

# Validate package name syntax
BAD_PKGS=$(printf '%s\n' "$PKGS" | grep -vE '^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$' || true)
if [ -n "$BAD_PKGS" ]; then
  echo "Error: File contains invalid package syntax:" >&2
  printf '%s\n' "$BAD_PKGS" | sed 's/^/  /' >&2
  exit 1
fi

# Guard critical core Android packages
CORE_RE='^(android|android\.ext\.(services|shared)|com\.android\.sdksandbox|com\.android\.location\.fused|com\.android\.systemui|com\.android\.shell|com\.android\.phone|com\.android\.dialer|com\.android\.server\.telecom|com\.android\.settings|com\.android\.keyguard|com\.(google\.)?android\.(permissioncontroller|packageinstaller|ext\.services|ext\.shared|modulemetadata)|com\.google\.android\.overlay\.modules.*|com\.android\.providers\.(telephony|media|downloads|settings)|com\.qualcomm\.qti\.telephonyservice|com\.mediatek\.telephony)$'
CORE_VIOLATIONS=$(printf '%s\n' "$PKGS" | grep -E "$CORE_RE" || true)

if [ -n "$CORE_VIOLATIONS" ]; then
  echo "CRITICAL SAFETY REFUSAL: The list contains protected core Android packages:" >&2
  printf '%s\n' "$CORE_VIOLATIONS" | sed 's/^/  /' >&2
  echo "These packages cannot be removed without bricking the device or losing dialer/emergency services." >&2
  exit 1
fi

# Create backup directory & snapshot before modifying
TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
BACKUP_DIR="backups/backup_${TIMESTAMP}"
mkdir -p "$BACKUP_DIR"

echo "[*] Creating safety backup in $BACKUP_DIR..."
adb shell pm list packages -f > "$BACKUP_DIR/installed_packages.txt"
adb shell pm list packages -d > "$BACKUP_DIR/disabled_packages.txt"
adb shell getprop > "$BACKUP_DIR/getprop.txt"

# Prepare automated undo / restore script
RESTORE_SCRIPT="$BACKUP_DIR/restore.sh"
cat << 'EOF' > "$RESTORE_SCRIPT"
#!/usr/bin/env bash
# Automated restore script generated by CleanYourPhone
set -euo pipefail
echo "Restoring packages..."
EOF
chmod +x "$RESTORE_SCRIPT"

# Fetch currently installed packages on device for fast lookup
INSTALLED_CACHE=$(adb shell pm list packages | sed 's/^package://' | tr -d '\r')

TOTAL_COUNT=$(printf '%s\n' "$PKGS" | wc -l | tr -d ' ')
CURRENT=0
REMOVED_COUNT=0
SKIPPED_COUNT=0

echo "[*] Processing $TOTAL_COUNT packages..."

# Universal debloat action functions supporting legacy & modern Android
disable_package() {
  local target="$1"
  local out
  out=$(adb shell pm disable-user --user 0 "$target" 2>&1 | tr -d '\r')
  if [[ "$out" =~ "new state" || "$out" =~ "disabled" ]]; then
    return 0
  fi
  out=$(adb shell pm disable "$target" 2>&1 | tr -d '\r')
  if [[ "$out" =~ "new state" || "$out" =~ "disabled" ]]; then
    return 0
  fi
  out=$(adb shell pm hide "$target" 2>&1 | tr -d '\r')
  if [[ "$out" =~ "true" || "$out" =~ "Hidden" ]]; then
    return 0
  fi
  return 1
}

while IFS= read -r pkg; do
  [ -z "$pkg" ] && continue
  CURRENT=$((CURRENT + 1))

  # Check if package is installed on the phone
  if ! printf '%s\n' "$INSTALLED_CACHE" | grep -qx "$pkg"; then
    echo "[$CURRENT/$TOTAL_COUNT] Skipped: $pkg (not installed on this OS build)"
    SKIPPED_COUNT=$((SKIPPED_COUNT + 1))
    continue
  fi

  if [ "$DRY_RUN" -eq 1 ]; then
    echo "[$CURRENT/$TOTAL_COUNT] [DRY RUN] Would $MODE: $pkg"
    continue
  fi

  # Record universal restoration command
  echo "adb shell cmd package install-existing $pkg 2>/dev/null || adb shell pm install-existing $pkg 2>/dev/null || adb shell pm enable $pkg 2>/dev/null || adb shell pm unhide $pkg 2>/dev/null || true" >> "$RESTORE_SCRIPT"

  if [ "$MODE" = "uninstall" ]; then
    OUT=$(adb shell pm uninstall -k --user 0 "$pkg" 2>&1 | tr -d '\r')
    if [[ "$OUT" =~ "Success" ]]; then
      echo "[$CURRENT/$TOTAL_COUNT] Uninstalled: $pkg"
      REMOVED_COUNT=$((REMOVED_COUNT + 1))
    else
      # If uninstall fails on modern or legacy OS, gracefully fall back to universal disable
      if disable_package "$pkg"; then
        echo "[$CURRENT/$TOTAL_COUNT] Disabled (fallback): $pkg"
        REMOVED_COUNT=$((REMOVED_COUNT + 1))
      else
        echo "[$CURRENT/$TOTAL_COUNT] Protected by OS build: $pkg"
      fi
    fi
  else
    if disable_package "$pkg"; then
      echo "[$CURRENT/$TOTAL_COUNT] Disabled: $pkg"
      REMOVED_COUNT=$((REMOVED_COUNT + 1))
    else
      echo "[$CURRENT/$TOTAL_COUNT] Protected by OS build: $pkg"
    fi
  fi

done <<< "$PKGS"

echo "echo 'Restore complete.'" >> "$RESTORE_SCRIPT"

# Copy restore script to root convenience link
cp "$RESTORE_SCRIPT" restore_last_session.sh
chmod +x restore_last_session.sh

echo "=========================================================="
echo " Debloat Completed Successfully!"
echo " Total examined : $TOTAL_COUNT"
echo " Removed/Disabled: $REMOVED_COUNT"
echo " Already absent : $SKIPPED_COUNT"
echo " Restore script : ./restore_last_session.sh"
echo " Backup snapshot: $BACKUP_DIR/"
echo "=========================================================="
